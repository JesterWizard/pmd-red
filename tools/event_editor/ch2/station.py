#!/usr/bin/env python3
"""Build chapter 2's station file, events/sky/scenes/sky_d02p01_scenes.scene,
from the translator's draft (documentation/Features/SkyChapter2.md, "What
plays"). Run from the repository root after

    python3 tools/event_editor/eos_import.py EOS.nds --chapter2 events/sky/draft/ch2
    python3 tools/event_editor/eos_import.py EOS.nds --chapter2-station \\
        events/sky/draft/ch2/sky_d02p01_scenes.scene

It
1. puts group 0, free roam on B2F (tools/event_editor/ch2/free_roam.scene,
   made by hand), in place of the draft's placeholder group 0;
2. applies the hand edits below (tuned in the emulator);
3. formats the file (scenes.py fmt), gives every DEBUGINFO its own line
   number and checks the names (scenes.py check --names).

Edits made in the emulator belong in HAND below (or in the translator), so a
rerun keeps them.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DRAFT = ROOT / "events/sky/draft/ch2/sky_d02p01_scenes.scene"
OUT = ROOT / "events/sky/scenes/sky_d02p01_scenes.scene"
FREE_ROAM = Path(__file__).resolve().parent / "free_roam.scene"
SCENES = [sys.executable, str(ROOT / "tools/event_editor/scenes.py")]

PLACEHOLDER = '''script g0_s0_station control=ENTER_CONTROL type=SCRIPT_TYPE_01   # placeholder (made by hand)
    DEBUGINFO
    SELECT_MAP SKY_GUILD_B2F
    JUMP_SCRIPT COMMON_ENTER
end
'''
PLACEHOLDER_SECTORS = '''sectors g0
    sector station=0
end
'''
FREE_ROAM_SECTORS = '''sectors g0
    sector events=g0_s0_evts station=0
    sector actors=g0_s1_lives objects=g0_s1_objs
    sector actors=g0_s2_lives
end
'''
DRAFT_HEADER = '''# Explorers of Sky chapter 2 on its station gs180 (SkyChapter2.md), in play order.
# Draft: translated by tools/event_editor/eos_import.py --chapter2-station; group 0
# (free roam) is hand-made. Hand-tune it; `TODO eos` marks what was not translated.
'''
HEADER = '''# Explorers of Sky demake, chapter 2 (documentation/Features/SkyChapter2.md):
# the one station file of every chapter-2 map (Wigglytuff's Guild, Drenched
# Bluff). gMapScriptTable points them all at gs180, Red's Thunderwave Cave
# entrance slot, which the sky build does not use otherwise. Group 0 is free
# roam on B2F (made by hand); groups 1-27 are EoS's acting scripts in play
# order, first translated by `tools/event_editor/eos_import.py EOS.nds
# --chapter2-station` and then tuned in the emulator. The event scripts that
# chain them are in src/data/ground/sky/sky_ch2_events.h. Generated by
# tools/event_editor/ch2/station.py: edit that (or the translator), not this.
#
#   group 0  free roam on B2F (EoS G01P04A enter00, station UM02)
'''

# (group, old, new): hand edits over the translator's output. `old` must occur
# exactly once in that group.
HAND = [
    # m02a0113: EoS's Quick Tip about saving on the bed: the GBA has no bed.
    (9, '''    WAIT 30
    FANFARE_PLAY 207   # EoS me_Play(7)
    MSG_NPC who=-1 text="{CENTER_ALIGN}Exploration Team\\n{CENTER_ALIGN}Quick Tip"   # EoS message_Explanation
    # eos: CallCommon(CORO_MESSAGE_CLOSE_WAIT_FUNC); (the next line follows)
    MSG_NPC who=-1 text="{CENTER_ALIGN}You can save a record of your progress\\n{CENTER_ALIGN}by climbing onto your bed from now on."   # EoS message_Explanation
    MSG_NPC who=-1 text="{CENTER_ALIGN}So whenever you want to save your\\n{CENTER_ALIGN}progress, just climb onto your bed."   # EoS message_Explanation
    TEXTBOX_CLEAR
    WAIT 60
''', '''    WAIT 30
    # EoS: me_Play(7) and its Quick Tip ("You can save a record of your progress by
    # climbing onto your bed from now on"): the GBA has no bed to save on.
    WAIT 60
'''),
    # m02a0302: the board and the team under it. EoS centres the view on the board
    # (256x192); on the GBA's 160 lines the team would stand behind the text box, so
    # the view sits 24 px lower: the board at the top, the team just above the box.
    (13, "    SKY_CAMERA_SET x=228 y=152   # EoS camera_SetMyself<performer 0>\n",
     "    SKY_CAMERA_SET x=228 y=176   # EoS camera_SetMyself<performer 0> (24 px lower: the team over the text box)\n"),
]


def replace_once(s, old, new, what):
    if s.count(old) != 1:
        sys.exit(f"station.py: {what}: {s.count(old)} matches (want 1) for:\n{old}")
    return s.replace(old, new)


def group_span(s, n):
    """(start, end) of group n: its station script and its actors' scripts."""
    a = s.index(f"# group {n}: EoS")
    m = re.search(r"# group \d+: EoS|^stations$", s[a + 10:], re.M)
    return a, a + 10 + m.start()


def main():
    s = DRAFT.read_text()
    s = replace_once(s, PLACEHOLDER, FREE_ROAM.read_text(), "group 0")
    s = replace_once(s, PLACEHOLDER_SECTORS, FREE_ROAM_SECTORS, "group 0's sectors")
    s = replace_once(s, DRAFT_HEADER, HEADER, "header")
    for n, old, new in HAND:
        a, b = group_span(s, n)
        s = s[:a] + replace_once(s[a:b], old, new, f"group {n}") + s[b:]
    OUT.write_text(s)
    subprocess.run(SCENES + ["fmt", str(OUT)], check=True, stdout=subprocess.DEVNULL)
    # every DEBUGINFO records its own line of the scene file
    lines = OUT.read_text().split("\n")
    for i, ln in enumerate(lines):
        m = re.fullmatch(r"    DEBUGINFO(?: line=\d+)?(\s*#.*)?", ln)
        if m:
            lines[i] = f"    DEBUGINFO line={i + 1}" + (m.group(1) or "")
    OUT.write_text("\n".join(lines))
    subprocess.run(SCENES + ["check", "--names", str(OUT)], check=True)


if __name__ == "__main__":
    main()
