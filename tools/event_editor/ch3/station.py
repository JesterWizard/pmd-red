#!/usr/bin/env python3
"""Build chapter 3's station file, events/sky/scenes/sky_d02p02_scenes.scene,
from the translator's drafts (documentation/Features/SkyChapter3.md, "What
plays"). Run from the repository root after

    python3 tools/event_editor/eos_import.py EOS.nds --chapter3-station \\
        events/sky/draft/ch3/sky_d02p02_scenes.scene
    python3 tools/event_editor/ch3/free_roam.py EOS.nds   # events/sky/draft/ch3/free_roam.scene

It
1. puts groups 0-12, the free roam (free_roam.scene: the hub, then one group a
   map), in place of the draft's placeholders;
2. applies the hand edits below (tuned in the emulator);
3. formats the file (scenes.py fmt), gives every DEBUGINFO its own line
   number and checks the names (scenes.py check --names).

Edits made in the emulator belong in HAND below (or in the translators), so a
rerun keeps them.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DRAFT = ROOT / "events/sky/draft/ch3/sky_d02p02_scenes.scene"
FREE_ROAM = ROOT / "events/sky/draft/ch3/free_roam.scene"
OUT = ROOT / "events/sky/scenes/sky_d02p02_scenes.scene"
SCENES = [sys.executable, str(ROOT / "tools/event_editor/scenes.py")]
FREE_ROAM_GROUPS = range(0, 13)

DRAFT_HEADER = '''# Explorers of Sky chapter 3 on its station gs181 (SkyChapter3.md), in play order.
# Draft: translated by tools/event_editor/eos_import.py --chapter3-station; groups 0-19
# (free roam) are hand-made. Hand-tune it; `TODO eos` marks what was not translated.
'''
HEADER = '''# Explorers of Sky demake, chapter 3 (documentation/Features/SkyChapter3.md):
# the one station file of every chapter-3 map (Treasure Town, the crossroads,
# the guild by day, Mt. Bristle, the visions; the guild's maps under their own
# map ids, MAP_SKY_GUILD_*_CH3). gMapScriptTable points them all at gs181,
# Red's Thunderwave Cave end slot, which the sky build does not use otherwise.
# Groups 0-12 are the free roam (tools/event_editor/ch3/free_roam.py: group 0
# the hub every map's enter goes through, then one group a map); groups 20-66
# are EoS's acting scripts in play order, translated by
# `tools/event_editor/eos_import.py EOS.nds --chapter3-station` and tuned in the
# emulator. The event scripts that chain them are in
# src/data/ground/sky/sky_ch3_events.h. Generated by
# tools/event_editor/ch3/station.py: edit that (or the translators), not this.
'''

# (group, old, new): hand edits over the translator's output. `old` must occur
# exactly once in that group.
HAND = [
]


def replace_once(s, old, new, what):
    if s.count(old) != 1:
        sys.exit(f"station.py: {what}: {s.count(old)} matches (want 1) for:\n{old}")
    return s.replace(old, new)


def group_span(s, n):
    """(start, end) of group n: its station script and its actors' scripts."""
    a = s.index(f"# group {n}: EoS")
    m = re.search(r"# group \d+: EoS|^stations$", s[a + 10:], re.M)
    return a, a + 10 + m.start()


def cut_from(s, n, start, end_rows):
    """Group n's station: drop everything from the line `start` (exactly one) to the end of
    the station script and end it with end_rows."""
    a, b = group_span(s, n)
    g = s[a:b]
    i = g.index(start)
    if g.count(start) != 1:
        sys.exit(f"station.py: group {n}: {g.count(start)} matches for {start!r}")
    j = g.index("\nend\n", i)
    g = g[:i] + end_rows + g[j:]
    return s[:a] + g + s[b:]


def main():
    s = DRAFT.read_text()
    fr = FREE_ROAM.read_text()
    s = replace_once(s, DRAFT_HEADER, HEADER, "header")
    # the free roam's groups in place of the placeholders
    first = None
    for g in FREE_ROAM_GROUPS:
        ph = re.search(rf"\nscript g{g}_s0_station control=ENTER_CONTROL type=SCRIPT_TYPE_01   # placeholder "
                       rf"\(made by hand\)\n(?:    .*\n)*end\n", s)
        if not ph:
            sys.exit(f"station.py: no placeholder for group {g}")
        if first is None:
            first = ph.start()
            s = s[:ph.start()] + "\n@@FREE_ROAM@@\n" + s[ph.end():]
        else:
            s = s[:ph.start()] + "\n" + s[ph.end():]
        s = replace_once(s, f"\nsectors g{g}\n    sector station={g}\nend\n", "\n", f"group {g}'s sectors")
    # the free roam's sectors go with the others (after the stations list), in group order
    secs = re.findall(r"^sectors g\d+\n(?:    .*\n)*end\n", fr, re.M)
    for b in secs:
        fr = fr.replace(b, "")
    s = replace_once(s, "\nsectors g13\n", "\n" + "\n".join(secs) + "\nsectors g13\n", "the sectors")
    s = s.replace("@@FREE_ROAM@@", fr)
    for n, old, new in HAND:
        a, b = group_span(s, n)
        s = s[:a] + replace_once(s[a:b], old, new, f"group {n}") + s[b:]
    s = cuts(s)
    # labels are a byte: every script's labels numbered from 0 (the free roam's are not yet)
    sys.path.insert(0, str(ROOT / "tools/event_editor"))
    import eos_import
    import scenes
    s = scenes.serialize(eos_import.renumber_labels(scenes.parse(s)))
    OUT.write_text(s)
    subprocess.run(SCENES + ["fmt", str(OUT)], check=True, stdout=subprocess.DEVNULL)
    # every DEBUGINFO records its own line of the scene file
    lines = OUT.read_text().split("\n")
    for i, ln in enumerate(lines):
        m = re.fullmatch(r"    DEBUGINFO(?: line=\d+)?(\s*#.*)?", ln)
        if m:
            lines[i] = f"    DEBUGINFO line={i + 1}" + (m.group(1) or "")
    OUT.write_text("\n".join(lines))
    subprocess.run(SCENES + ["check", "--names", str(OUT)], check=True)


def cuts(s):
    """Scenes the GBA ends earlier than EoS (SkyChapter3.md, "What plays")."""
    # m03a0801 / m03a0901: Drowzee's closing speech and the boss transition play in the
    # dungeon (the peak's cutscene, src/dungeon_cutscene_mt_bristle.c): the ground scene
    # stops before them; the event script enters the peak
    peak = ("    TEXTBOX_CLEAR\n"
            "    # EoS goes on with Drowzee's closing speech, bgm_Stop, two white flashes, the boss\n"
            "    # transition and main_EnterDungeon(5): on the GBA the peak's cutscene plays them and\n"
            "    # the event script enters the peak (SKY_MT_BRISTLE_CLEARED_EVENT)\n"
            "    RET")
    s = cut_from(s, 44, '    MSG_NPC who=DROWZEE text=" This should be a laugh.', peak)
    s = cut_from(s, 45, '    MSG_NPC who=DROWZEE text=" You foolish pests.', peak)
    # m03a1002: EoS ends on "Bidoof's Wish" unlocked (p15p01a, back_SetBackEffect(4)): the demo
    # has no special episodes
    s = cut_from(s, 47, '    MSG_NPC who=-1 text="{CENTER_ALIGN}Wait...{WAIT_PRESS}',
                 "    TEXTBOX_CLEAR\n"
                 "    # EoS: \"Wait... There's one more message.\", Bidoof's family at their lodge (p15p01a) and\n"
                 "    # \"The Special Episode 'Bidoof's Wish' has been unlocked!\": the demo has no special episodes\n"
                 "    FADE_OUT wait=TRUE frames=30\n"
                 "    RET")
    return s


if __name__ == "__main__":
    main()
