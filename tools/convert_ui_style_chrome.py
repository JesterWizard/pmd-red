#!/usr/bin/env python3
"""Convert graphics/custom/ui_style/sky_chrome.png into src/data/ui_style_sky_chrome.h.

The PNG is an indexed strip of 8x8 tiles whose pixel values are font bank-15
palette slots (0 = transparent, 1 = window fill, 13/14/15 = frame dark / mid /
light). Each tile replaces one or more font chrome tiles when ui_style is Sky.

Run after editing the PNG:  python3 tools/convert_ui_style_chrome.py
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "graphics" / "custom" / "ui_style" / "sky_chrome.png"
DST = ROOT / "src" / "data" / "ui_style_sky_chrome.h"

# Tile order in the PNG -> font chrome tile ids it replaces.
TILES = [
    ("corner", (0x2D8, 0x2E8)),      # window top-left corner, NORMAL + TYPE_4 (flips give the rest)
    ("top", (0x2D9, 0x2E9)),         # window top edge (flipped vertically for the bottom)
    ("left", (0x2DA, 0x2EA)),        # window left edge (flipped horizontally for the right)
    ("dialogue_top", (0x2E4,)),      # dialogue box top-left corner (unused vanilla tile slot)
    ("dialogue_bottom", (0x2E5,)),   # dialogue box bottom-left corner (unused vanilla tile slot)
    ("portrait_corner", (0x2DC,)),   # portrait frame corner (band hugs the portrait)
    ("portrait_top", (0x2DD,)),      # portrait frame top edge
    ("portrait_left", (0x2DE,)),     # portrait frame left edge
    # Header-window tab pieces: vanilla shapes recoloured to the Sky band
    # (outer mid, light band, dark inner line).
    ("header_corner", (0x2E0,)),
    ("header_top", (0x2E1,)),
    ("header_join", (0x2E7,)),
    ("header_tab_a", (0x2DF,)),
    ("header_tab_b", (0x2E3,)),
    ("header_tab_corner", (0x297,)),   # also the WINDOW_TYPE_7 portrait top edge
    ("header_tab_side", (0x2EF,)),
]


def tile_bytes(img: Image.Image, index: int) -> bytes:
    out = bytearray()
    for y in range(8):
        for x in range(0, 8, 2):
            lo = img.getpixel((index * 8 + x, y))
            hi = img.getpixel((index * 8 + x + 1, y))
            if lo > 15 or hi > 15:
                raise SystemExit(f"{SRC}: tile {index} uses palette index > 15")
            out.append(lo | (hi << 4))
    return bytes(out)


def main() -> None:
    img = Image.open(SRC)
    if img.mode != "P":
        raise SystemExit(f"{SRC}: expected an indexed (P mode) PNG")
    if img.size != (8 * len(TILES), 8):
        raise SystemExit(f"{SRC}: expected {8 * len(TILES)}x8, got {img.size[0]}x{img.size[1]}")

    data: list[bytes] = []
    ids: list[int] = []
    for i, (_, targets) in enumerate(TILES):
        raw = tile_bytes(img, i)
        for tile_id in targets:
            data.append(raw)
            ids.append(tile_id)

    lines = [
        "/* Generated by tools/convert_ui_style_chrome.py from",
        " * graphics/custom/ui_style/sky_chrome.png — do not edit by hand. */",
        "",
        f"#define UI_STYLE_SKY_CHROME_TILE_COUNT {len(ids)}",
        "",
        "static const u16 sUiStyleSkyChromeTileIds[UI_STYLE_SKY_CHROME_TILE_COUNT] = {",
        "    " + ", ".join(f"0x{t:03X}" for t in ids) + ",",
        "};",
        "",
        "static const u8 sUiStyleSkyChromeTiles[UI_STYLE_SKY_CHROME_TILE_COUNT * 32] ALIGNED(4) = {",
    ]
    for tile_id, raw in zip(ids, data):
        lines.append(f"    /* 0x{tile_id:03X} */")
        for row in range(0, 32, 16):
            lines.append("    " + ", ".join(f"0x{b:02X}" for b in raw[row:row + 16]) + ",")
    lines.append("};")
    DST.write_text("\n".join(lines) + "\n")
    print(f"Wrote {DST.relative_to(ROOT)} ({len(ids)} tiles)")


if __name__ == "__main__":
    main()
